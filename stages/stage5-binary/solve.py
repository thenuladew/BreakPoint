#!/usr/bin/env python3

def decode_password():
    # The XOR key is 0x5A
    xor_key = 0x5A
    enc_pass = [0x35, 0x37, 0x3f, 0x3d, 0x3b, 0x5, 0x2a, 0x28, 0x35, 0x2e, 0x35, 0x39, 0x35, 0x36, 0x5, 0x33, 0x34, 0x33, 0x2e, 0x33, 0x3b, 0x2e, 0x3f, 0x3e]
    
    password = "".join([chr(b ^ xor_key) for b in enc_pass])
    print(f"Decoded Password: {password}")
    return password

def decode_flag():
    # The XOR key is 0x42
    xor_key = 0x42
    enc_flag = [0x0, 0x12, 0x39, 0x3a, 0x2d, 0x30, 0x1d, 0x2d, 0x20, 0x24, 0x37, 0x31, 0x21, 0x23, 0x36, 0x2b, 0x2d, 0x2c, 0x1d, 0x30, 0x27, 0x34, 0x27, 0x30, 0x31, 0x27, 0x26, 0x3f]
    
    flag = "".join([chr(b ^ xor_key) for b in enc_flag])
    print(f"Decoded Flag: {flag}")

if __name__ == "__main__":
    decode_password()
    decode_flag()

